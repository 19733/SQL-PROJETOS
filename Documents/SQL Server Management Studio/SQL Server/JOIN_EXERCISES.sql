CREATE TABLE [TABELA DE VENDEDORES](

MATRICULA VARCHAR (5) NOT NULL PRIMARY KEY,
NOME VARCHAR (100),
[PERCENTUAL DE COMISSAO] FLOAT,
[DATA VENDA] DATE,
QUANTIDADE INT
);

CREATE TABLE VENDAS (
    ID_VENDA INT NOT NULL PRIMARY KEY,
    CPF VARCHAR(11),
    [CODIGO DO PRODUTO] INT,
    MATRICULA INT,
    [DATA VENDA] DATE,
    QUANTIDADE INT
);

