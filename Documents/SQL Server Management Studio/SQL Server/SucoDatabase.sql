    [TABELA DE CLIENTES].NOME AS [Nome Cliente],
    [TABELA DE VENDEDORES].NOME AS [Nome Vendedor],
    [TABELA DE PRODUTO].[NOME DO PRODUTO] AS Produto,
    VENDAS.QUANTIDADE,
    VENDAS.DATA_VENDA
