LEFT JOIN [TABELA DE CLIENTES] ON VENDAS.CPF = [TABELA DE CLIENTES].CPF
LEFT JOIN [TABELA DE PRODUTO] ON VENDAS.CODIGO_DO_PRODUTO = [TABELA DE PRODUTO].[CODIGO DO PRODUTO]
LEFT JOIN [TABELA DE VENDEDORES] ON VENDAS.MATRICULA = [TABELA DE VENDEDORES].MATRICULA;

