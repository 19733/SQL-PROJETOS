UPDATE [TABELA DE CLIENTES] 
SET 
    RUA = COALESCE(RUA, 'Endereço Não Cadastrado'),
    COMPLEMENTO = COALESCE(COMPLEMENTO, 'Informação Não Fornecida'),
    BAIRRO = COALESCE(BAIRRO, 
        CASE ESTADO 
            WHEN 'RJ' THEN 'Centro'
            WHEN 'SP' THEN 'Centro'
            WHEN 'MG' THEN 'Savassi'
            WHEN 'PR' THEN 'Centro Cívico'
            WHEN 'BA' THEN 'Comércio'
            ELSE 'Centro'
        END),
    CEP = COALESCE(CEP,
        CASE ESTADO 
            WHEN 'SP' THEN '01000000'
            WHEN 'PR' THEN '80000000' 
            WHEN 'MG' THEN '30000000'
            WHEN 'RJ' THEN '20000000'
            WHEN 'BA' THEN '40000000'
            ELSE '00000000'
        END),
    [DATA DE NASCIMENTO] = COALESCE([DATA DE NASCIMENTO], '1980-01-01'),
    IDADE = COALESCE(IDADE, DATEDIFF(YEAR, COALESCE([DATA DE NASCIMENTO], '1980-01-01'), GETDATE())),
    SEXO = COALESCE(SEXO, 
        CASE 
            WHEN ESTADO IN ('SP', 'MG') THEN 'F'
            ELSE 'M'
        END),
    [VOLUME MINIMO] = COALESCE([VOLUME MINIMO], 1000.00),
    [PRIMEIRA COMPRA] = COALESCE([PRIMEIRA COMPRA], 0)
WHERE RUA IS NULL 
   OR COMPLEMENTO IS NULL 
   OR BAIRRO IS NULL 
   OR CEP IS NULL 
   OR [DATA DE NASCIMENTO] IS NULL 
   OR IDADE IS NULL 
   OR SEXO IS NULL 
   OR [VOLUME MINIMO] IS NULL 
   OR [PRIMEIRA COMPRA] IS NULL;


